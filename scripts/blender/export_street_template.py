"""Run after node scripts/export-street.mjs; recreate actual game meshes in Blender."""
import bpy,json,math,sys,argparse
from pathlib import Path
parser=argparse.ArgumentParser()
parser.add_argument("--input",default="/tmp/street-meshes.json")
parser.add_argument("--output",default=str(Path(__file__).resolve().parents[2]/"location-editing/street-template.blend"))
args=parser.parse_args(sys.argv[sys.argv.index("--")+1:] if "--" in sys.argv else [])
from mathutils import Vector
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
scene=bpy.context.scene
scene.unit_settings.system='METRIC'
materials={}
def mat(color):
 if color not in materials:
  m=bpy.data.materials.new(color);m.diffuse_color=tuple(int(color[i:i+2],16)/255 for i in (1,3,5))+(1,);m.use_nodes=True
  # Convert sRGB palette to linear, like Three.js.
  rgb=tuple(v/12.92 if v<=.04045 else ((v+.055)/1.055)**2.4 for v in m.diffuse_color[:3])
  m.node_tree.nodes.get('Principled BSDF').inputs['Base Color'].default_value=rgb+(1,)
  m.node_tree.nodes.get('Principled BSDF').inputs['Roughness'].default_value=.92
  materials[color]=m
 return materials[color]
def collection(name):
 c=bpy.data.collections.new(name);scene.collection.children.link(c);return c
def move(o,c):
 for old in list(o.users_collection):old.objects.unlink(o)
 c.objects.link(o)
for chunk in json.load(open(args.input)):
 idx=chunk['index'];c=collection('EDIT_26m_MAIN' if idx==0 else 'REFERENCE_NEIGHBOR_'+str(idx))
 for n,data in enumerate(chunk['meshes']):
  mesh=bpy.data.meshes.new('StreetMesh');mesh.from_pydata(data['vertices'],[],data['faces']);mesh.update()
  o=bpy.data.objects.new(('Sign' if data['sign'] else 'Street')+f'_{idx}_{n:03}',mesh);c.objects.link(o);o.data.materials.append(mat('#244338' if data['sign'] else data['color']))
  o.hide_select=idx!=0
  if data['sign']:
   bpy.ops.object.text_add(location=(idx*26+8,3.925,3),rotation=(math.pi/2,0,0));t=bpy.context.object;t.name='Sign_text';t.data.body=['ДВОРОВЫЕ ИСТОРИИ','УЛИЦА НАДЕЖДЫ','ДАЛЬШЕ — БОЛЬШЕ'][idx+1];t.data.align_x='CENTER';t.data.align_y='CENTER';t.data.size=.24;t.data.materials.append(mat('#f4e4b5'));move(t,c);t.hide_select=idx!=0
c=collection('GUIDES_DO_NOT_EXPORT');c.hide_render=True
for name,loc,scale in [('SECTION_START',(0,0,.02),(.02,9,.02)),('SECTION_END',(26,0,.02),(.02,9,.02)),('PLAY_AREA',(13,-.05,.01),(13,2.05,.01))]:
 bpy.ops.mesh.primitive_cube_add(size=2,location=loc);o=bpy.context.object;o.name=name;o.scale=scale;o.display_type='WIRE';o.hide_render=True;move(o,c)
bpy.ops.mesh.primitive_cube_add(size=1,location=(8,0,1));o=bpy.context.object;o.name='HERO_HEIGHT_2m_REFERENCE';o.scale=(.6,.45,2);o.display_type='WIRE';o.hide_render=True;move(o,c)
for name,loc in [('SECTION_ORIGIN',(0,0,0)),('NEXT_SECTION_ORIGIN',(26,0,0))]:
 o=bpy.data.objects.new(name,None);o.location=loc;o.empty_display_type='ARROWS';c.objects.link(o)
c=collection('PREVIEW_CAMERA_AND_LIGHTS')
bpy.ops.object.camera_add(location=(13,-9.1,3.73));cam=bpy.context.object;cam.name='Game_camera_reference';cam.rotation_euler=(Vector((13,0,1))-cam.location).to_track_quat('-Z','Y').to_euler();cam.data.type='PERSP';cam.data.lens_unit='FOV';cam.data.sensor_fit='VERTICAL';cam.data.sensor_height=24;cam.data.lens=24/(2*math.tan(math.radians(42)/2));scene.camera=cam;move(cam,c)
bpy.ops.object.light_add(type='SUN',location=(0,-8,12));o=bpy.context.object;o.rotation_euler=(.4,-.5,-.4);o.data.energy=3;move(o,c)
scene.world.color=(.35,.35,.35);scene.render.resolution_x=1365;scene.render.resolution_y=768;scene.render.resolution_percentage=100
notes=bpy.data.texts.new('READ_ME');notes.write('Editable copy of src/world.js. Units: metres. Blender X=game X, Blender Y=-game Z, Blender Z=game Y. Main section X 0..26. Walk area Blender Y -2.1..2.0. Neighbours are locked references. Guides and preview camera are NOT game assets. Bottle meshes are layout references; gameplay pickups remain generated by code. Signs recreated as editable text. Move/edit main collection; keep section origin and seamless edges. See README in location-editing. No gameplay changes are applied automatically.\n')
for area in bpy.context.screen.areas:
 if area.type=='VIEW_3D':
  area.spaces.active.region_3d.view_distance=35
  area.spaces.active.region_3d.view_location=(13,0,1)
bpy.ops.object.select_all(action='DESELECT')
bpy.context.preferences.filepaths.save_version=0
bpy.ops.wm.save_as_mainfile(filepath=args.output)
print('Street template saved',len(bpy.data.objects),'objects')
